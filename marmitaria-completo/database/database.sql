-- Documentação do que foi criado, o banco funciona na nuvem.

-- (1) CRIAÇÃO DAS TABELAS - SQL
-- Tabelas foram criadas em table editor no supabase.

-- (1.1) tabela CATEGORIAS
create table public.categorias (
  id bigint generated by default as identity not null,
  nome text null default ''::text,
  imagem text null,
  ativa boolean not null default true,
  constraint categorias_pkey primary key (id),
  constraint categorias_nome_key unique (nome),
  constraint categorias_nome_tamanho check (
    ((length( TRIM(both from nome)) >= 2 )
      and (length(TRIM(both from nome)))
      )),
  constraint nome_categoria_naovazio check (
    (length(TRIM(both from nome)) > 0))
) TABLESPACE pg_default;

create unique INDEX IF not exists categorias_nome_unico on public.categorias using btree (
  lower(TRIM(both from nome))
) TABLESPACE pg_default;

create unique INDEX IF not exists categorias_nome_unique on public.categorias using btree (lower(nome)) TABLESPACE pg_default;


-- (1.2) tabela PRATOS
create table public.pratos (
  id bigint generated by default as identity not null,
  nome text not null default ''::text,
  descricao text null default ''::text,
  preco numeric not null,
  categoria_id bigint not null,
  disponivel boolean not null default true,
  imagem text null,
  constraint pratos_pkey primary key (id),
  constraint pratos_nome_key unique (nome),
  constraint pratos_categoria_id_fkey foreign KEY (categoria_id) references categorias (id) on delete RESTRICT,
  constraint pratos_nome_tamanho check (
    ((length( TRIM(both from nome)) >= 2)
      and 
      (length(TRIM( both from nome)) <= 80))),

  constraint check_preco_positivo check ((preco > (0)::numeric)),
  constraint pratos_preco_positivo check ((preco > (0)::numeric)),
  constraint nome_pratos_naovazio check (
    (length( TRIM( both from nome)) > 0)),

  constraint pratos_descricao_tamanho check (
    ((descricao is null)
      or (length(descricao) <= 300)))
) TABLESPACE pg_default;

create index IF not exists pratos_categoria_id_idx on public.pratos using btree (categoria_id) TABLESPACE pg_default;

create unique INDEX IF not exists pratos_nome_categoria_unique on public.pratos using btree (categoria_id, lower(nome)) TABLESPACE pg_default;



-- (2) VALIDAÇÕES E RESTRIÇÕES

-- (2.1) validações
-- preço acima de 0, nome categoria e prato não pode ser vazio

ALTER TABLE pratos
ADD CONSTRAINT check_preco_positivo
CHECK (preco>0);

ALTER TABLE categorias
ADD CONSTRAINT nome_categoria_naovazio
CHECK (length(trim(nome))>0);

ALTER TABLE pratos
ADD CONSTRAINT nome_pratos_naovazio
CHECK (length(trim(nome))>0);

-- impedir nomes repetidos independente se letras minúsculas, maiúsculas 
-- ou com espaço
CREATE UNIQUE INDEX categorias_nome_unico
ON public.categorias (lower(trim(nome)));

-- (2.2) limites de caracteres

-- categorias limite de 2 a 50
ALTER TABLE public.categorias
ADD CONSTRAINT categorias_nome_tamanho
CHECK (length(trim(nome)) BETWEEN 2 AND 50);

-- pratos limite 2 a 80
ALTER TABLE public.pratos
ADD CONSTRAINT pratos_nome_tamanho
CHECK (length(trim(nome)) BETWEEN 2 AND 80);

-- descrição dos pratos limite até 300
ALTER TABLE public.pratos
ADD CONSTRAINT pratos_descricao_tamanho
CHECK (
    descricao IS NULL OR length(descricao) <= 300
);


